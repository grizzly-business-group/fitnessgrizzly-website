import type { NextConfig } from "next";

/*
 * Static export for GitHub Pages (Nov 2026). GitHub Pages serves files only: no server, no Proxy, no
 * redirects() / headers(), no image optimizer. Instead:
 *   - every route is prerendered to out/<route>/index.html (trailingSlash) — gym pages via generateStaticParams
 *   - old Wix URLs get small redirect pages (lib/data/legacy-redirects.json → scripts/postbuild.mjs)
 *   - unknown URLs, incl. retired /baraboo and /copy-of-berlin, get out/404.html (real 404 status on Pages)
 *   - images: custom loader (lib/image-loader.ts) + WebP sizes pre-generated by scripts/postbuild.mjs
 *   - security policy: <meta http-equiv="Content-Security-Policy"> + referrer meta in app/layout.tsx
 *   - indexing: SITE_INDEXING=true at build → meta robots + robots.txt (lib/indexing.ts)
 *   - NEXT_PUBLIC_BASE_PATH="/<repo>" only for the github.io preview; empty on www.fitnessgrizzly.com
 */
const basePath = (process.env.NEXT_PUBLIC_BASE_PATH || "").replace(/\/+$/, "");

const nextConfig: NextConfig = {
  output: "export",
  trailingSlash: true,
  ...(basePath ? { basePath } : {}),
  poweredByHeader: false,
  devIndicators: { position: "bottom-right" },
  images: {
    loader: "custom",
    loaderFile: "./lib/image-loader.ts",
    // scripts/postbuild.mjs generates a WebP for every one of these widths — keep the two in step.
    deviceSizes: [640, 828, 1080, 1280, 1600, 1920, 2400],
    imageSizes: [64, 128, 256, 384],
    qualities: [75, 85],
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
